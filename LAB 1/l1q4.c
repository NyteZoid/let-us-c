// program to display size of data type

#include <stdio.h>
int main() {
	printf("The size of int datatype is %ld\n", sizeof(int));
	printf("The size of char datatype is %ld\n", sizeof(char));
	printf("The size of float datatype is %ld\n", sizeof(float));
	printf("The size of double datatype is %ld\n", sizeof(double));
	printf("The size of long int datatype is %ld\n", sizeof(long int));
	printf("The size of long double datatype is %ld\n", sizeof(long double));
	return 0;
}
